// Samples the code-stream palette from the logo's opal (spec §4: never hand-picked).
// Writes src/codestream/palette.generated.ts. Re-run when the logo changes.
import { writeFileSync } from 'node:fs';
import sharp from 'sharp';
import { converter, formatHex } from 'culori';

const SRC = '../Brand Assets/Brand_logo_original.jpg';
const ART_BOTTOM = 625; // rows below this are the wordmark
const K = 12, ITERS = 20;

const { data, info } = await sharp(SRC).removeAlpha().raw().toBuffer({ resolveWithObject: true });
const toLab = converter('lab');
const toLch = converter('lch');

const pts = [];
for (let y = 0; y < Math.min(ART_BOTTOM, info.height); y += 2) {
  for (let x = 0; x < info.width; x += 2) {
    const i = (y * info.width + x) * 3;
    const r = data[i], g = data[i + 1], b = data[i + 2];
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b);
    if (mn < 232 && mx - mn > 25 && mx > 120) {
      const c = toLab({ mode: 'rgb', r: r / 255, g: g / 255, b: b / 255 });
      if (c.l > 55) pts.push([c.l, c.a, c.b]); // opal is light; drops the navy wing highlight
    }
  }
}

// Deterministic k-means (mulberry32, seed 1).
let s = 1;
const rand = () => { s |= 0; s = (s + 0x6d2b79f5) | 0; let t = Math.imul(s ^ (s >>> 15), 1 | s); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
let cent = Array.from({ length: K }, () => pts[Math.floor(rand() * pts.length)].slice());
for (let it = 0; it < ITERS; it++) {
  const sum = cent.map(() => [0, 0, 0, 0]);
  for (const p of pts) {
    let best = 0, bd = Infinity;
    for (let k = 0; k < K; k++) {
      const d = (p[0] - cent[k][0]) ** 2 + (p[1] - cent[k][1]) ** 2 + (p[2] - cent[k][2]) ** 2;
      if (d < bd) { bd = d; best = k; }
    }
    const t = sum[best]; t[0] += p[0]; t[1] += p[1]; t[2] += p[2]; t[3]++;
  }
  cent = sum.map((t, k) => (t[3] ? [t[0] / t[3], t[1] / t[3], t[2] / t[3]] : cent[k]));
}

const hex = cent
  .map(([l, a, b]) => ({ hex: formatHex({ mode: 'lab', l, a, b }), h: toLch({ mode: 'lab', l, a, b }).h ?? 0 }))
  .sort((p, q) => p.h - q.h)
  .map((p) => p.hex);

const out = `// Generated by scripts/sample-palette.mjs from ${SRC.split('/').pop()} (k-means, k=${K}, ${pts.length} opal pixels).
// Do not edit by hand. Regenerated ${new Date().toISOString().slice(0, 10)}.
export const STREAM_PALETTE: readonly string[] = ${JSON.stringify(hex, null, 2)} as const;
`;
writeFileSync('src/codestream/palette.generated.ts', out);
console.log(hex.join(' '));
